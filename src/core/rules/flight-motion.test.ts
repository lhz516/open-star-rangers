// Expectations come from docs/original/formats/executable.md (movement stage and integration, numbers on the movement
// path, P3-06/01) through the exact-rational reference of flight-motion.test-support.ts, or are written out by hand;
// none is generated by the code under test.

/** f32 m × 2^e, written out exactly. */
const f32 = (m: number, e: number): number => m * 2 ** e;
/** f32(n ÷ d), rounded independently of Math.fround. */
const f32Of = (n: bigint, d: bigint): number => float32OfRational(n, d, 'nearest');

const IDENTITY = Object.freeze([1, 0, 0, 0, 1, 0, 0, 0, 1]) as unknown as Matrix3;
/** Rows of no special shape: neither unit nor orthogonal, so every product shows. */
const ROWS = Object.freeze([
  f32(13421773, -24), f32(-5033165, -23), f32(3, -2),
  f32(-7, -4), f32(10066330, -24), f32(11744051, -24),
  f32(8388609, -24), f32(-3, -3), f32(13631488, -24),
]) as unknown as Matrix3;

const record = (overrides: Partial<MotionRecord> = {}): MotionRecord => ({ atB8: 64, atBC: 8, atC0: 12, atC4: 0, atC8: 1, ...overrides });

const axis = (rate = 0, enabled = false) => ({ rate, enabled });

function block(overrides: Partial<SteeredMovementBlock> = {}): SteeredMovementBlock {
  return {
    mode: 'craft',
    speed: 48,
    commandedSpeed: 48,
    atCommandedSpeed: true,
    speedRatio: 0.75,
    steering: { pitch: axis(), yaw: axis(), roll: axis() },
    timedRotation: { pitch: null, yaw: null, roll: null },
    impulse: null,
    locked: false,
    disturbance: null,
    ...overrides,
  };
}

const motion = (overrides: Partial<SteeredMovementBlock> = {}, position: Vec3 = { x: 1234.5, y: -987.25, z: 1000 }, orientation: Matrix3 = IDENTITY): SteeredMotion =>
  ({ position, orientation, block: block(overrides) });

/** A deep copy that keeps the sign of zeros, for checking that an integrator left its input alone. */
const copyOf = (value: SteeredMotion): SteeredMotion => structuredClone(value);

/** Integrates by the block's mode and checks the result against the reference and the input's immutability. */
function expectReference(input: SteeredMotion, rules: MotionRecord, step: MotionStep): SteeredMotion {
  const before = copyOf(input);
  const result = (input.block.mode === 'craft' ? integrateCraft : integrateWarp)(input, rules, step);
  expect(result).toEqual(referenceFrame(before, rules, step));
  expect(input).toEqual(before);
  return result;
}

const STEPS = [0, 2, 4, 6] as const;

describe('rotation helpers 0x228cc, 0x22a50, 0x22990 (P3-06 AC-02, M-01)', () => {
  it.each(ROTATION_AXES.flatMap((rotationAxis) => [0.3, -1.125, f32(1, -10), 2.5].map((angle) => [rotationAxis, angle] as const)))(
    'rotates about %s by %d: the two other rows from their old values, one double sum and one f32 store per component',
    (rotationAxis, angle) => {
      const rows = rotateRows(ROWS, rotationAxis, Math.fround(angle));
      expect(rows).toEqual(referenceRotation(ROWS, rotationAxis, Math.fround(angle)));
      const kept = { pitch: 0, yaw: 1, roll: 2 }[rotationAxis];
      expect(rows.slice(3 * kept, 3 * kept + 3)).toEqual(ROWS.slice(3 * kept, 3 * kept + 3));
      expect(Object.isFrozen(rows)).toBe(true);
    },
  );

  it('changes rows 2 and 3 about row 1, rows 1 and 3 about row 2, rows 1 and 2 about row 3, with the same signs', () => {
    // c = s = f32(sin π/4) = f32(cos π/4); a′ = c·a + s·b and b′ = c·b − s·a from the identity.
    const angle = Math.fround(Math.PI / 4);
    const c = f32(11863283, -24);
    const s = f32(11863283, -24);
    expect(rotateRows(IDENTITY, 'pitch', angle)).toEqual([1, 0, 0, 0, c, s, 0, -s, c]);
    expect(rotateRows(IDENTITY, 'yaw', angle)).toEqual([c, 0, s, 0, 1, 0, -s, 0, c]);
    expect(rotateRows(IDENTITY, 'roll', angle)).toEqual([c, s, 0, -s, c, 0, 0, 0, 1]);
  });

  it('keeps the rows at angle 0 but for signed zeros, which round to nearest makes +0, and never renormalises', () => {
    const rows = Object.freeze([-0, 1, 0, -0, 0, 1, 2, 0, 0]) as unknown as Matrix3;
    const rotated = rotateRows(rows, 'pitch', 0);
    expect(rotated).toEqual([-0, 1, 0, 0, 0, 1, 2, 0, 0]);
    expect(Object.is(rotated[3], 0)).toBe(true);
    // The row of length 2 stays so after any rotation.
    expect(rotateRows(rows, 'yaw', Math.fround(0.5)).slice(3, 6)).toEqual([-0, 0, 1]);
  });
});

describe('the step of an integration (P3-06 AC-02; spec 行为与边界)', () => {
  it.each([
    [0, 0, 0, 0],
    [2, 64, 1 / 32, 1],
    [4, 6, 1 / 16, 6 / 64],
    [6, 3, 6 / 64, 3 / 64],
    // 2^30 + 1 clock units are not an f32 number of seconds: t rounds to nearest.
    [2, 2 ** 30 + 1, 1 / 32, 2 ** 24],
    // The largest step whose seconds are still an f32.
    [2 ** 25, 0, 2 ** 19, 0],
  ])('takes %i clock units at clock %i as dt %d s and t %d s', (units, clock, seconds, time) => {
    expect(motionStep(units, clock)).toEqual({ seconds, time });
  });

  it.each([[-2, 0], [1.5, 0], [2 ** 53, 0], [2 ** 25 + 2, 0], [2, -1], [2, 0.5], [Number.NaN, 0]])('faults on %d clock units at clock %d', (units, clock) => {
    expectFault(() => motionStep(units, clock), 'invariant-violated', 'flight-motion.step');
  });

  it.each([
    { seconds: -1 / 32, time: 1 },
    { seconds: -0, time: 1 },
    { seconds: Number.NaN, time: 1 },
    { seconds: 0.1, time: 1 },
    { seconds: 1 / 32, time: -1 },
    { seconds: 1 / 32, time: Number.POSITIVE_INFINITY },
  ])('makes both integrators fault on the step %o', (step) => {
    expectFault(() => integrateCraft(motion(), record(), step), 'invariant-violated', 'flight-motion.step');
    expectFault(() => integrateWarp(motion(), record(), step), 'invariant-violated', 'flight-motion.step');
  });
});

describe('craft integrator 0x222f0, mode 0 (P3-06 AC-02, M-01)', () => {
  it.each(STEPS)('flies straight along row 3 at step %i with the speed and the rows unchanged', (units) => {
    const result = expectReference(motion(), record(), motionStep(units, 64));
    // 48 × dt is exact here: only z moves.
    expect(result.position).toEqual({ x: 1234.5, y: -987.25, z: 1000 + (48 * units) / 64 });
    expect(result.orientation).toEqual(IDENTITY);
    expect([result.block.speed, result.block.speedRatio, result.block.atCommandedSpeed]).toEqual([48, 0.75, true]);
  });

  it.each(STEPS)('advances along a general row 3 with two roundings per component at step %i', (units) => {
    expectReference(motion({ speed: f32(12345679, -17) }, { x: f32(-12582913, -7), y: 1.5, z: f32(9999999, -3) }, ROWS), record(), motionStep(units, 64));
  });

  it.each(STEPS)('accelerates toward a higher commanded speed at +0xBC and moves with the speed before the update, step %i', (units) => {
    const input = motion({ speed: 40, commandedSpeed: 47, atCommandedSpeed: false, speedRatio: 0.625 });
    const result = expectReference(input, record({ atBC: f32(13421773, -20) }), motionStep(units, 64));
    expect(result.position.z).toBe(1000 + (40 * units) / 64);
    if (units > 0) expect(result.block.speed).toBeGreaterThan(40);
    expect(result.block.atCommandedSpeed).toBe(false);
  });

  it.each(STEPS)('decelerates toward a lower commanded speed at +0xC0, step %i', (units) => {
    const result = expectReference(motion({ speed: 48, commandedSpeed: 30, atCommandedSpeed: false }), record({ atC0: f32(10066330, -21) }), motionStep(units, 64));
    expect(result.block.atCommandedSpeed).toBe(false);
  });

  it('arrives on a long step: the speed takes the commanded value bit for bit, the flag is set and the ratio follows', () => {
    const result = expectReference(motion({ speed: 40, commandedSpeed: f32(12345679, -18), atCommandedSpeed: false }), record({ atBC: 8 }), motionStep(64, 64));
    expect(result.block).toMatchObject({ speed: f32(12345679, -18), atCommandedSpeed: true, speedRatio: f32Of(12345679n, 64n << 18n) });
    // The position took the old speed for the whole second.
    expect(result.position.z).toBe(1040);
    const down = expectReference(motion({ speed: 48, commandedSpeed: 47.5, atCommandedSpeed: false }), record({ atC0: 1 }), motionStep(64, 64));
    expect(down.block).toMatchObject({ speed: 47.5, atCommandedSpeed: true });
  });

  it('decides the arrival on the double v, not on its f32 store', () => {
    // speed 1 − 2^−24, +0xBC × dt = 2^−24 + 2^−30: v = 1 + 2^−30 is past 1 although f32(v) = 1.
    const input = motion({ speed: 1 - 2 ** -24, commandedSpeed: 1, atCommandedSpeed: false });
    const result = expectReference(input, record({ atBC: 2 ** -19 + 2 ** -25 }), motionStep(2, 64));
    expect(result.block).toMatchObject({ speed: 1, atCommandedSpeed: true });
    // Decelerating: speed 1 + 2^−23, +0xC0 × dt = 2^−23 + 2^−30, v = 1 − 2^−30 is below 1 although f32(v) = 1.
    const down = expectReference(motion({ speed: 1 + 2 ** -23, commandedSpeed: 1, atCommandedSpeed: false }), record({ atC0: 2 ** -18 + 2 ** -25 }), motionStep(2, 64));
    expect(down.block).toMatchObject({ speed: 1, atCommandedSpeed: true });
  });

  it('does not count reaching the commanded speed exactly: the next step decelerates and arrives, or stays without +0xC0', () => {
    // v = 1 + 2^−23 − 2^−30 is below the commanded 1 + 2^−23, and its f32 store is the commanded speed.
    const commanded = 1 + 2 ** -23;
    const rules = record({ atBC: 127 * 2 ** -25, atC0: 4 });
    const reached = expectReference(motion({ speed: 1, commandedSpeed: commanded, atCommandedSpeed: false }), rules, motionStep(2, 64));
    expect(reached.block).toMatchObject({ speed: commanded, atCommandedSpeed: false });
    const arrived = expectReference(reached, rules, motionStep(2, 66));
    expect(arrived.block).toMatchObject({ speed: commanded, atCommandedSpeed: true });
    const staying = expectReference(reached, record({ atC0: 0 }), motionStep(2, 66));
    expect(staying.block).toMatchObject({ speed: commanded, atCommandedSpeed: false });
  });

  it('never moves the speed toward a higher commanded speed without +0xBC, nor toward a lower one without +0xC0', () => {
    const up = expectReference(motion({ speed: 40, commandedSpeed: 48, atCommandedSpeed: false }), record({ atBC: 0 }), motionStep(2, 64));
    expect(up.block).toMatchObject({ speed: 40, atCommandedSpeed: false });
    const down = expectReference(motion({ speed: 48, commandedSpeed: 40, atCommandedSpeed: false }), record({ atC0: 0 }), motionStep(2, 64));
    expect(down.block).toMatchObject({ speed: 48, atCommandedSpeed: false });
  });

  it('keeps a speed above any maximum falling at +0xC0 per second: nothing caps it', () => {
    let current = motion({ speed: 200, commandedSpeed: 50, atCommandedSpeed: false, speedRatio: 3.125 });
    for (let tick = 1; tick <= 3; tick++) current = expectReference(current, record({ atC0: 16 }), motionStep(2, 64 + 2 * tick));
    expect(current.block).toMatchObject({ speed: 198.5, atCommandedSpeed: false, speedRatio: f32Of(1985n, 640n) });
  });

  it('freezes the speed and the ratio while the commanded speed is reached', () => {
    const result = expectReference(motion({ speed: 40, commandedSpeed: 48, speedRatio: 0.5 }), record(), motionStep(2, 64));
    expect(result.block).toMatchObject({ speed: 40, commandedSpeed: 48, speedRatio: 0.5 });
  });

  it.each([0, -64])('leaves the ratio when +0xB8 is %d, not positive', (atB8) => {
    const result = expectReference(motion({ speed: 40, commandedSpeed: 48, atCommandedSpeed: false, speedRatio: 0.5 }), record({ atB8 }), motionStep(2, 64));
    expect(result.block).toMatchObject({ speed: 40.25, speedRatio: 0.5 });
  });

  it.each([1, 0])('turns with factor dt when +0xC8 is non-zero, f32(ratio × dt) otherwise (+0xC8 = %i)', (atC8) => {
    const steering = { pitch: axis(f32(-12582912, -24), true), yaw: axis(f32(9227469, -23), true), roll: axis(-1.25, true) };
    const result = expectReference(motion({ steering, speedRatio: f32(11184811, -24) }, undefined, ROWS), record({ atC8 }), motionStep(4, 64));
    expect(result.orientation).not.toEqual(ROWS);
  });

  it('applies the steady rotations about rows 1, 2 and 3 in that order, each about the rows the previous one left', () => {
    const steering = { pitch: axis(0.75, true), yaw: axis(-0.5, true), roll: axis(1.5, true) };
    const result = expectReference(motion({ steering }), record(), motionStep(2, 64));
    const [p, y, r] = [0.75, -0.5, 1.5].map((rate) => Math.fround(rate / 32));
    expect(result.orientation).toEqual(referenceRotation(referenceRotation(referenceRotation(IDENTITY, 'pitch', p), 'yaw', y), 'roll', r));
    // Another order gives other rows.
    expect(result.orientation).not.toEqual(referenceRotation(referenceRotation(referenceRotation(IDENTITY, 'roll', r), 'yaw', y), 'pitch', p));
  });

  it('keeps a disabled axis\'s rate without applying it', () => {
    const result = expectReference(motion({ steering: { pitch: axis(0.75), yaw: axis(-0.5), roll: axis(1.5) } }), record(), motionStep(2, 64));
    expect(result.orientation).toEqual(IDENTITY);
    expect(result.block.steering).toEqual({ pitch: axis(0.75), yaw: axis(-0.5), roll: axis(1.5) });
  });

  describe('+0xC4 coupling of the yaw turn into row 3', () => {
    const ratio = f32(11184811, -24);

    it('turns row 3 by f32(yaw × ratio) with the yaw on and the roll off', () => {
      const result = expectReference(motion({ speedRatio: ratio, steering: { pitch: axis(), yaw: axis(1.25, true), roll: axis(3) } }), record({ atC4: 1 }), motionStep(2, 64));
      const yawed = referenceRotation(IDENTITY, 'yaw', Math.fround(1.25 / 32));
      expect(result.orientation).toEqual(referenceRotation(yawed, 'roll', Math.fround(Math.fround(1.25 * ratio) / 32)));
    });

    it('adds the enabled roll rate to the coupled rate before the f32 store', () => {
      const steering = { pitch: axis(), yaw: axis(-1.25, true), roll: axis(f32(3, -3), true) };
      expectReference(motion({ speedRatio: ratio, steering }, undefined, ROWS), record({ atC4: 1 }), motionStep(6, 64));
    });

    it('takes the ratio this step\'s speed update left', () => {
      const steering = { pitch: axis(), yaw: axis(2, true), roll: axis() };
      const result = expectReference(motion({ speed: 40, commandedSpeed: 48, atCommandedSpeed: false, speedRatio: 0.625, steering }), record({ atC4: 1, atC8: 0 }), motionStep(4, 64));
      expect(result.block.speedRatio).toBe(f32Of(40n * 64n + 8n * 4n, 64n * 64n));
    });

    it.each([
      ['+0xC4 is 0', 0, false],
      ['the yaw is off', 1, true],
    ] as const)('leaves row 3 to its own steady rate when %s', (_, atC4, yawOff) => {
      const steering = { pitch: axis(), yaw: axis(1.25, !yawOff), roll: axis(0.5, true) };
      const result = expectReference(motion({ steering }), record({ atC4 }), motionStep(2, 64));
      const yawed = yawOff ? IDENTITY : referenceRotation(IDENTITY, 'yaw', Math.fround(1.25 / 32));
      expect(result.orientation).toEqual(referenceRotation(yawed, 'roll', Math.fround(0.5 / 32)));
    });
  });

  describe('timed rotations (P3-07 writes them; movement consumes them)', () => {
    const timed = (rate: number, decay: number, end: number) => ({ rate, decay, end });

    it.each(STEPS)('rotates by the rate before this step\'s decay, then decays it, step %i', (units) => {
      const result = expectReference(
        motion({ timedRotation: { pitch: timed(1.5, f32(13176795, -22), 9), yaw: timed(-2, -f32(13176795, -23), 9), roll: timed(0.25, 0.125, 9) } }, undefined, ROWS),
        record(),
        motionStep(units, 64),
      );
      if (units > 0) expect(result.block.timedRotation.pitch!.rate).toBeLessThan(1.5);
    });

    it('adds the enabled steady rate before the f32 store, and decays only the timed rate', () => {
      const steering = { pitch: axis(0.5, true), yaw: axis(-0.75, true), roll: axis(0.125, true) };
      const result = expectReference(motion({ steering, timedRotation: { pitch: timed(1, 0.5, 9), yaw: null, roll: timed(-1, -0.5, 9) } }), record(), motionStep(2, 64));
      expect(result.block.timedRotation).toEqual({ pitch: timed(1 - 1 / 64, 0.5, 9), yaw: null, roll: timed(-1 + 1 / 64, -0.5, 9) });
      expect(result.block.steering).toEqual(steering);
    });

    it('rounds the sum of the timed and the steady rate to f32 before the turn factor scales it', () => {
      const steering = { pitch: axis(f32(7654321, -27), true), yaw: axis(f32(-9876543, -26), true), roll: axis(f32(5555555, -25), true) };
      const timedRotation = { pitch: timed(f32(12345677, -23), 0.5, 9), yaw: timed(f32(-8765433, -24), -0.25, 9), roll: timed(f32(10000001, -24), 1, 9) };
      expectReference(motion({ steering, timedRotation, speedRatio: f32(11184811, -24) }, undefined, ROWS), record({ atC8: 0 }), motionStep(2, 64));
    });

    it('ends once t is past the end, after rotating and decaying: t equal to the end keeps it', () => {
      const input = motion({ timedRotation: { pitch: null, yaw: timed(1, 0.5, 2), roll: null } });
      // Clock 128 is t = 2: still on. Clock 130 is t = 2.03125: rotated, then ended.
      const kept = expectReference(input, record(), motionStep(2, 128));
      expect(kept.block.timedRotation.yaw).toEqual(timed(1 - 1 / 64, 0.5, 2));
      const ended = expectReference(input, record(), motionStep(2, 130));
      expect(ended.block.timedRotation.yaw).toBeNull();
      expect(ended.orientation).toEqual(kept.orientation);
    });

    it('lets a timed roll replace the coupled turn', () => {
      const steering = { pitch: axis(), yaw: axis(1.25, true), roll: axis() };
      const result = expectReference(motion({ steering, timedRotation: { pitch: null, yaw: null, roll: timed(0.5, 0.25, 9) } }), record({ atC4: 1 }), motionStep(2, 64));
      const yawed = referenceRotation(IDENTITY, 'yaw', Math.fround(1.25 / 32));
      expect(result.orientation).toEqual(referenceRotation(yawed, 'roll', 0.5 / 32));
    });

    it('carries the rate past zero on a step longer than the rate allows before the end clears it', () => {
      const result = expectReference(motion({ timedRotation: { pitch: timed(0.25, 0.5, 9), yaw: null, roll: null } }), record(), motionStep(64, 64));
      expect(result.block.timedRotation.pitch).toEqual(timed(-0.25, 0.5, 9));
    });
  });

  describe('impulse (P3-07 writes it; movement consumes it)', () => {
    const direction = { x: f32(-11863283, -24), y: 0, z: f32(11863283, -24) };

    it.each(STEPS)('displaces along its direction by the magnitude before the decay, then decays by 30/s, step %i', (units) => {
      const result = expectReference(motion({ impulse: { direction, magnitude: 40 } }, undefined, ROWS), record(), motionStep(units, 64));
      expect(result.block.impulse).toEqual({ direction, magnitude: 40 - (30 * units) / 64 });
    });

    it('ends when the decayed magnitude is below 0, and not at 0', () => {
      const ended = expectReference(motion({ impulse: { direction, magnitude: 0.5 } }), record(), motionStep(2, 64));
      expect(ended.block.impulse).toBeNull();
      expect(ended.position.x).toBe(Math.fround(1234.5 + Math.fround(direction.x * (0.5 / 32))));
      const atZero = expectReference(motion({ impulse: { direction, magnitude: 0.9375 } }), record(), motionStep(2, 64));
      expect(atZero.block.impulse).toEqual({ direction, magnitude: 0 });
    });
  });

  it('changes nothing at step 0 but the signs of zeros: nothing arrives, decays or ends', () => {
    const steering = { pitch: axis(0.5, true), yaw: axis(), roll: axis(-0.25, true) };
    const input = motion(
      {
        speed: 40, commandedSpeed: 48, atCommandedSpeed: false, speedRatio: 0.625, steering,
        timedRotation: { pitch: null, yaw: { rate: 1, decay: 0.5, end: 1 }, roll: null }, impulse: { direction: { x: 0, y: 1, z: 0 }, magnitude: 3 },
      },
      { x: -0, y: 5, z: -0 },
      Object.freeze([1, -0, 0, -0, 1, 0, 0, 0, 1]) as unknown as Matrix3,
    );
    const result = expectReference(input, record(), motionStep(0, 64));
    // −0 + +0 is +0 under round to nearest.
    expect(result.position).toEqual({ x: 0, y: 5, z: 0 });
    expect(result.orientation).toEqual([1, 0, 0, 0, 1, 0, 0, 0, 1]);
    expect(result.block).toEqual({ ...input.block, speedRatio: 0.625 });
  });

  it('follows the reference over 96 steps of turning, coupling, timed rotations ending and speed changes, drift included', () => {
    const steering = { pitch: axis(f32(-10066330, -24), true), yaw: axis(f32(14260634, -23), true), roll: axis(f32(5, -4), true) };
    const rules = record({ atC4: 1, atC8: 0, atBC: 6, atC0: 9 });
    const timedRotation = { pitch: { rate: f32(-9437185, -23), decay: -f32(13176795, -22), end: 1.25 }, yaw: null, roll: { rate: f32(12582913, -24), decay: 0.375, end: 2.5 } };
    let current = motion({ speed: 20, commandedSpeed: 60, atCommandedSpeed: false, speedRatio: 0.3125, steering, timedRotation }, { x: 100.25, y: -3, z: 7 }, ROWS);
    let expected = copyOf(current);
    for (let tick = 1; tick <= 96; tick++) {
      if (tick === 48) {
        current = { ...current, block: { ...current.block, commandedSpeed: 10, atCommandedSpeed: false } };
        expected = { ...expected, block: { ...expected.block, commandedSpeed: 10, atCommandedSpeed: false } };
      }
      const step = motionStep(tick % 3 === 0 ? 4 : 2, 2 * tick);
      current = integrateCraft(current, rules, step);
      expected = referenceFrame(expected, rules, step);
      expect(current).toEqual(expected);
    }
    expect(current.block.timedRotation).toEqual({ pitch: null, yaw: null, roll: null });
    // Without renormalisation the rows are no longer of unit length.
    const [a, b, c] = current.orientation;
    expect(a * a + b * b + c * c).not.toBe(1);
  });

  it('returns frozen pose values and a block detached from its input', () => {
    const input = motion({ steering: { pitch: axis(0.5, true), yaw: axis(), roll: axis() }, impulse: { direction: { x: 1, y: 0, z: 0 }, magnitude: 5 } });
    const result = integrateCraft(input, record(), motionStep(2, 64));
    expect(deepFrozen(result.position)).toBe(true);
    expect(deepFrozen(result.orientation)).toBe(true);
    result.block.steering.pitch.rate = 9;
    result.block.impulse!.magnitude = 9;
    expect(input.block.steering.pitch.rate).toBe(0.5);
    expect(input.block.impulse!.magnitude).toBe(5);
  });

  // The original unmasks overflow: an f32 store past the range traps even when the step then discards its value.
  const nearMaximum = FLOAT32_MAX - 2 ** 104;
  it.each([
    ['a position past the f32 range', motion({ speed: FLOAT32_MAX }, { x: 0, y: 0, z: FLOAT32_MAX }), record(), motionStep(2, 64)],
    ['a speed ratio past the f32 range', motion({ speed: 40, commandedSpeed: 48, atCommandedSpeed: false }), record({ atB8: 2 ** -149 }), motionStep(2, 64)],
    ['a non-finite speed', motion({ speed: Number.NaN }), record(), motionStep(2, 64)],
    ['a speed store past the range before the arrival replaces it', motion({ speed: nearMaximum, commandedSpeed: FLOAT32_MAX, atCommandedSpeed: false }), record({ atBC: 2 ** 110 }), motionStep(2, 64)],
    ['a turn factor past the range that no rotation uses', motion({ speedRatio: FLOAT32_MAX }), record({ atC8: 0 }), motionStep(2 ** 25, 64)],
    ['a decayed timed rate past the range of a rotation that ends', motion({ timedRotation: { pitch: { rate: 1, decay: FLOAT32_MAX, end: 1 }, yaw: null, roll: null } }), record(), motionStep(2 ** 25, 128)],
  ] as const)('faults on %s and returns nothing', (_, input, rules, step) => {
    const before = copyOf(input);
    expectFault(() => integrateCraft(input, rules, step), 'invariant-violated', 'flight-motion.result');
    expect(input).toEqual(before);
  });
});

describe('Warp integrator 0x22600, mode 3 (P3-06 AC-02, M-01; triggered by P3-09)', () => {
  const warp = (overrides: Partial<SteeredMovementBlock> = {}) => motion({ mode: 'warp', ...overrides }, { x: 5, y: 6, z: 7 }, ROWS);

  it.each(STEPS)('neither translates nor applies or decays an impulse, step %i', (units) => {
    const impulse = { direction: { x: 0, y: 0, z: 1 }, magnitude: 20 };
    const result = expectReference(warp({ speed: 0, commandedSpeed: 64, atCommandedSpeed: false, speedRatio: 0, impulse }), record({ atBC: 128 }), motionStep(units, 64));
    expect(result.position).toEqual({ x: 5, y: 6, z: 7 });
    expect(result.block.impulse).toEqual(impulse);
    expect(result.block.speed).toBe((128 * units) / 64);
    expect(result.block.speedRatio).toBe((128 * units) / 64 / 64);
  });

  it('arrives like mode 0, and the ratio is then speed ÷ commanded speed', () => {
    const result = expectReference(warp({ speed: 60, commandedSpeed: 64, atCommandedSpeed: false }), record({ atBC: 256, atB8: 0 }), motionStep(2, 64));
    expect(result.block).toMatchObject({ speed: 64, atCommandedSpeed: true, speedRatio: 1 });
  });

  it('leaves a speed at or above the commanded speed, and still takes the ratio from it', () => {
    for (const commandedSpeed of [40, 30]) {
      const result = expectReference(warp({ speed: 40, commandedSpeed, atCommandedSpeed: false, speedRatio: 0.5 }), record({ atC0: 100 }), motionStep(2, 64));
      expect(result.block).toMatchObject({ speed: 40, atCommandedSpeed: false, speedRatio: f32Of(40n, BigInt(commandedSpeed)) });
    }
  });

  it('keeps the speed and the ratio while the commanded speed is reached', () => {
    const result = expectReference(warp({ speed: 40, commandedSpeed: 0, speedRatio: 0.5 }), record(), motionStep(2, 64));
    expect(result.block).toMatchObject({ speed: 40, speedRatio: 0.5 });
  });

  it('turns like mode 0, coupling and timed rotations included', () => {
    const steering = { pitch: axis(0.5, true), yaw: axis(-1.25, true), roll: axis(0.25, true) };
    expectReference(
      warp({ speed: 10, commandedSpeed: 64, atCommandedSpeed: false, steering, timedRotation: { pitch: { rate: 1, decay: 0.5, end: 9 }, yaw: null, roll: null } }),
      record({ atC4: 1, atC8: 0, atBC: 32 }),
      motionStep(4, 64),
    );
  });

  it.each([[10, 0], [0, 0], [10, -0]])('faults on speed %d and a zero commanded speed %d with the flag clear (the unmasked divide)', (speed, commandedSpeed) => {
    expectFault(() => integrateWarp(warp({ speed, commandedSpeed, atCommandedSpeed: false }), record(), motionStep(2, 64)), 'invariant-violated', 'flight-motion.result');
  });

  it('faults on a rotated row past the f32 range', () => {
    const rows = Object.freeze([FLOAT32_MAX, 0, 0, FLOAT32_MAX, 0, 0, 0, 0, 1]) as unknown as Matrix3;
    expectFault(() => rotateRows(rows, 'roll', Math.fround(Math.PI / 4)), 'invariant-violated', 'flight-motion.result');
    expectFault(() => integrateWarp({ ...warp({ steering: { pitch: axis(), yaw: axis(), roll: axis(25.25, true) } }), orientation: rows }, record(), motionStep(2, 64)), 'invariant-violated', 'flight-motion.result');
  });
});
